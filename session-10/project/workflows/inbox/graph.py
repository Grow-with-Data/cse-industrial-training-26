"""Wire the inbox graph. One function returns it compiled.

    START -> triage -> split --Send x N--> orders | billing | policy | general -> compose -> END

    from workflows.inbox import build_inbox
    graph = build_inbox()
    graph.invoke({"ticket": ticket}, context=customer_for(ticket["from"]))

`uv run python -m workflows.inbox.graph` prints the topology and rewrites diagram.md.
That file is committed so a change to the wiring shows up in a diff.

THE ORDER IS IN THE EDGES
    In v6 the agent chose what to do next, on every run, and sometimes chose
    differently. Here triage always runs, split always follows it, every
    sub-issue always reaches a desk, and compose always runs last. None of that
    is a request to a model. It is the shape of the graph.

THE CUSTOMER IS CONTEXT
    `context_schema=Customer`, the same dataclass chat.py passes with `--as`.
    The caller supplies it on every invoke; every node can read it through its
    `runtime`, and no message can change it.
"""
from __future__ import annotations

from pathlib import Path

from langgraph.graph import END, START, StateGraph

from middleware import Customer
from workflows.inbox.nodes import (billing_desk, compose, general_desk, orders_desk,
                                   policy_desk, route_sub_issues, split, triage_node)
from workflows.inbox.state import InboxState

DESK_NODES = {
    "orders": orders_desk,
    "billing": billing_desk,
    "policy": policy_desk,
    "general": general_desk,
}


def build_inbox(checkpointer=None):
    """The compiled v7 graph. No checkpointer by default: one ticket in, one
    reply out, nothing to resume. Session 11 changes that."""
    builder = StateGraph(InboxState, context_schema=Customer)
    builder.add_node("triage", triage_node)
    builder.add_node("split", split)
    for name, desk in DESK_NODES.items():
        builder.add_node(name, desk)
    builder.add_node("compose", compose)

    builder.add_edge(START, "triage")
    builder.add_edge("triage", "split")
    # The fan-out. route_sub_issues returns a list of Send; the list of names is
    # only there so the drawing shows which desks it CAN reach.
    builder.add_conditional_edges("split", route_sub_issues, list(DESK_NODES))
    for name in DESK_NODES:
        builder.add_edge(name, "compose")       # the fan-in
    builder.add_edge("compose", END)
    return builder.compile(checkpointer=checkpointer)


def mermaid_text(graph) -> str:
    """The graph as plain mermaid that any previewer renders.

    LangGraph's draw_mermaid() output needs four repairs before a markdown
    previewer will draw it:
      - the `---config: flowchart---` header on top: some renderers refuse it;
      - `<p>...</p>` HTML inside node labels;
      - `:::first` class suffixes and `classDef` styling lines;
      - the ids `__start__` / `__end__`: markdown can read the double
        underscores as bold before mermaid ever sees them.
    The topology is untouched: same nodes, same edges, same dotted lines for
    the conditional fan-out."""
    text = graph.get_graph().draw_mermaid()
    if text.startswith("---"):
        text = text.split("---", 2)[2].lstrip()
    lines = ["graph TD"]
    for raw in text.splitlines():
        line = raw.strip().rstrip(";")
        if not line or line.startswith(("graph ", "classDef")):
            continue
        line = line.split(":::")[0]
        line = line.replace("<p>", "").replace("</p>", "")
        # `end` is a mermaid keyword, so the ids are neutral; the labels say START/END
        line = line.replace("__start__([__start__])", "graph_start([START])")
        line = line.replace("__end__([__end__])", "graph_end([END])")
        line = line.replace("__start__", "graph_start").replace("__end__", "graph_end")
        lines.append(f"    {line}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    mermaid = mermaid_text(build_inbox())
    print(mermaid)
    out = Path(__file__).with_name("diagram.md")
    out.write_text("# The v7 inbox graph\n\nGenerated by `uv run python -m workflows.inbox.graph`. "
                   "Do not edit by hand.\n\n```mermaid\n" + mermaid + "```\n", encoding="utf-8")
    print(f"wrote {out}")
